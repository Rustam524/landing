const I18N_STORAGE_KEY = 'algoritm_lang';
const I18N_DEFAULT_LANG = 'ru';

const I18N = {
  lang: I18N_DEFAULT_LANG,

  t(key) {
    const dict = I18N_TRANSLATIONS[this.lang] || I18N_TRANSLATIONS[I18N_DEFAULT_LANG];
    return (dict && dict[key] !== undefined) ? dict[key] : (I18N_TRANSLATIONS[I18N_DEFAULT_LANG][key] || key);
  },

  conversation() {
    return I18N_CONVERSATIONS[this.lang] || I18N_CONVERSATIONS[I18N_DEFAULT_LANG];
  },

  waLink(baseUrl, text) {
    return `${baseUrl}?text=${encodeURIComponent(text)}`;
  },

  apply(lang, options) {
    const opts = options || {};
    if (!I18N_TRANSLATIONS[lang]) lang = I18N_DEFAULT_LANG;
    this.lang = lang;

    try { localStorage.setItem(I18N_STORAGE_KEY, lang); } catch (e) { /* localStorage недоступен — не критично */ }

    document.documentElement.setAttribute('lang', lang === 'kz' ? 'kk' : 'ru');

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.innerHTML = this.t(key);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.setAttribute('placeholder', this.t(el.getAttribute('data-i18n-placeholder')));
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
      el.setAttribute('aria-label', this.t(el.getAttribute('data-i18n-aria-label')));
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
      el.setAttribute('alt', this.t(el.getAttribute('data-i18n-alt')));
    });

    const titleEl = document.getElementById('pageTitle');
    if (titleEl) titleEl.textContent = this.t('meta.title');
    const descEl = document.getElementById('pageDescription');
    if (descEl) descEl.setAttribute('content', this.t('meta.description'));

    // предзаполненный текст для всех WhatsApp-ссылок сайта; значение
    // атрибута — необязательный ключ перевода для своего текста
    // (например data-wa-link="wa.askText" у кнопки «Задать вопрос»),
    // без значения используется общий wa.defaultText
    document.querySelectorAll('[data-wa-link]').forEach(a => {
      const base = a.getAttribute('href').split('?')[0];
      const textKey = a.getAttribute('data-wa-link') || 'wa.defaultText';
      a.setAttribute('href', this.waLink(base, this.t(textKey)));
    });

    document.querySelectorAll('.lang-switch__btn').forEach(btn => {
      btn.classList.toggle('is-active', btn.getAttribute('data-lang') === lang);
    });

    if (!opts.silent) {
      document.dispatchEvent(new CustomEvent('algoritm:langchange', { detail: { lang } }));
    }
  },

  init() {
    let saved = null;
    try { saved = localStorage.getItem(I18N_STORAGE_KEY); } catch (e) { /* noop */ }
    const initialLang = saved && I18N_TRANSLATIONS[saved] ? saved : I18N_DEFAULT_LANG;
    this.apply(initialLang, { silent: true });

    document.querySelectorAll('.lang-switch__btn').forEach(btn => {
      btn.addEventListener('click', () => {
        const lang = btn.getAttribute('data-lang');
        if (lang !== this.lang) this.apply(lang);
      });
    });
  }
};

// ВАЖНО: top-level `const` в обычном (не module) скрипте НЕ становится
// свойством window — а script.js читает переводы именно через window.I18N.
// Без этой строки объект был недоступен снаружи, и телефон-мокап оставался
// пустым (пустой массив диалога), а WhatsApp-тексты/ошибки формы молча
// откатывались на английские ключи вместо переводов.
window.I18N = I18N;

document.addEventListener('DOMContentLoaded', () => I18N.init());
